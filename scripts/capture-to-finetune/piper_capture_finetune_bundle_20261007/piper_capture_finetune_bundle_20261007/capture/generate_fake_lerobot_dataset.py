"""Generate an all-zero LeRobot dataset matching the aligned Piper X schema.

This is for validating the OpenPI/LeRobot loading and fine-tuning path only.
It is not robot data and must never be used to train a real policy.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create an all-zero Piper X LeRobot debug dataset")
    parser.add_argument("--root", type=Path, required=True, help="New dataset directory")
    parser.add_argument("--repo-id", default="local/piper_x_fake_zero")
    parser.add_argument("--task", default="debug no-op task")
    parser.add_argument("--episodes", type=int, default=2)
    parser.add_argument("--frames-per-episode", type=int, default=64)
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=480)
    parser.add_argument("--images", action="store_true", help="Store image frames rather than encoded videos")
    args = parser.parse_args()
    args.root = args.root.resolve()
    if args.root.exists():
        parser.error(f"--root must not already exist: {args.root}")
    if min(args.episodes, args.frames_per_episode, args.width, args.height) <= 0:
        parser.error("episodes, frames-per-episode, width, and height must all be positive")
    return args


def main() -> None:
    args = parse_args()
    # Generating data needs LeRobot; displaying --help does not.
    import numpy as np
    from lerobot.common.datasets.lerobot_dataset import LeRobotDataset

    from .aligned_capture import FPS, STATE_NAMES, lerobot_features

    args.root.parent.mkdir(parents=True, exist_ok=True)
    base_rgb = np.zeros((args.height, args.width, 3), dtype=np.uint8)
    wrist_rgb = np.zeros((args.height, args.width, 3), dtype=np.uint8)
    state = np.zeros(7, dtype=np.float32)
    action = np.zeros(7, dtype=np.float32)
    dataset = LeRobotDataset.create(
        repo_id=args.repo_id,
        fps=FPS,
        root=args.root,
        robot_type="piper_x",
        features=lerobot_features(base_rgb, wrist_rgb, use_videos=not args.images),
        use_videos=not args.images,
    )
    raw_dir = args.root / "piper_raw"
    raw_dir.mkdir()
    manifest = {
        "schema_version": 1,
        "synthetic": True,
        "warning": "All values are zero. This dataset is for pipeline debugging only, never real-policy training.",
        "fps": FPS,
        "base_camera": "synthetic D435i RGB uint8",
        "wrist_camera": "synthetic DaBai DC1 RGB uint8",
        "state_names": STATE_NAMES,
        "action_source": "synthetic_zero",
        "action": "float32[7] all zeros",
        "image": f"RGB uint8[{args.height},{args.width},3] all zeros",
    }
    (args.root / "piper_capture_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    for episode_index in range(args.episodes):
        log_path = raw_dir / f"episode_{episode_index:06d}_alignment.jsonl"
        with log_path.open("w", encoding="utf-8") as raw_log:
            for frame_index in range(args.frames_per_episode):
                dataset.add_frame(
                    {
                        "observation.images.base": base_rgb,
                        "observation.images.wrist": wrist_rgb,
                        "observation.state": state,
                        "action": action,
                        "task": args.task,
                        # Timestamp is generated by LeRobot as frame_index / FPS.
                    }
                )
                raw_log.write(
                    json.dumps(
                        {
                            "synthetic": True,
                            "episode_index": episode_index,
                            "frame_index": frame_index,
                            "target_timestamp_ns": frame_index * round(1_000_000_000 / FPS),
                            "base_skew_ns": 0,
                            "wrist_skew_ns": 0,
                            "arm_skew_ns": 0,
                        }
                    )
                    + "\n"
                )
        dataset.save_episode()
        print(f"Saved synthetic episode {episode_index + 1}/{args.episodes}")

    print(f"Created {dataset.num_episodes} episodes / {dataset.num_frames} frames at {args.root}")


if __name__ == "__main__":
    main()
