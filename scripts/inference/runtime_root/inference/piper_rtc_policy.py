"""JAX OpenPI Pi0/pi0.5 RTC policy, preserving checkpoint transforms.

The public action space is [six absolute joint angles in rad, closedness].
Reference actions use this same physical space; only this policy converts
them to the normalized observation-relative space of the action expert.

Requires the OpenPI GPU environment. The wrapper uses a few private Policy
members whose names are verified against the project's OpenPI checkout.
"""

from __future__ import annotations

import hashlib
import pathlib
import threading
import time
from typing import Any

import flax.nnx as nnx
import jax
import jax.numpy as jnp
import numpy as np
from openpi_client import base_policy

from openpi.models import model as model_lib
from openpi.models import pi0
from openpi.policies import policy_config
from openpi.shared import nnx_utils
from openpi.training import config as training_config


PHYSICAL_ACTION_DIM = 7


def guidance_weight(t: jax.Array, maximum: float) -> jax.Array:
    """Kinetix pseudoinverse-guidance scale in OpenPI's reversed time.

    Kinetix evolves noise->data with u=0->1. Here t=1-u. Combining its
    c * inv_r2 gives ((1-t)^2+t^2)/(t*(1-t)). Protect both endpoints before
    division so even inactive/zero-weight guidance never produces NaNs.
    """
    safe_t = jnp.clip(t, 1e-5, 1.0 - 1e-5)
    beta = (safe_t**2 + (1.0 - safe_t) ** 2) / (safe_t * (1.0 - safe_t))
    return jnp.minimum(beta, maximum)


class RTCSampler(nnx.Module):
    """Reuse a loaded Pi0 model; cache its visual/language prefix once.

    Finite beta prevents endpoint infinities; it does not guarantee Euler
    stability. The initial settings (10 steps, maximum guidance 5) use
    OpenPI's original step count and a conservative guidance scale, not
    validated optimal parameters. Validate latency and guidance residuals
    together against the actual model before live execution.
    """

    def __init__(self, model: pi0.Pi0, *, num_steps: int, max_guidance: float):
        self.model = model
        self.num_steps = num_steps
        self.max_guidance = max_guidance

    def sample_actions(
        self,
        rng: jax.Array,
        observation: model_lib.Observation,
        reference: jax.Array,
        weights: jax.Array,
        noise: jax.Array,
    ) -> jax.Array:
        model = self.model
        observation = model_lib.preprocess_observation(None, observation, train=False)
        batch_size = observation.state.shape[0]
        # rng is retained in the sampler interface; noise is generated by the
        # policy so callers can compare RTC and unguided sampling identically.
        del rng
        prefix_tokens, prefix_mask, prefix_ar_mask = model.embed_prefix(observation)
        prefix_attention = pi0.make_attn_mask(prefix_mask, prefix_ar_mask)
        prefix_positions = jnp.cumsum(prefix_mask, axis=1) - 1
        _, kv_cache = model.PaliGemma.llm(
            [prefix_tokens, None], mask=prefix_attention, positions=prefix_positions
        )

        def velocity(x_t: jax.Array, t: jax.Array) -> jax.Array:
            suffix, suffix_mask, suffix_ar_mask, adarms_cond = model.embed_suffix(
                observation, x_t, jnp.broadcast_to(t, (batch_size,))
            )
            suffix_attention = pi0.make_attn_mask(suffix_mask, suffix_ar_mask)
            prefix_attention = jnp.broadcast_to(
                prefix_mask[:, None, :], (batch_size, suffix.shape[1], prefix_mask.shape[1])
            )
            attention = jnp.concatenate([prefix_attention, suffix_attention], axis=-1)
            positions = jnp.sum(prefix_mask, axis=-1)[:, None] + jnp.cumsum(suffix_mask, axis=-1) - 1
            (_, suffix_out), _ = model.PaliGemma.llm(
                [None, suffix],
                mask=attention,
                positions=positions,
                kv_cache=kv_cache,
                adarms_cond=[None, adarms_cond],
            )
            # The restored action head emits bfloat16 while the integration
            # state/noise is float32.  Keep the ODE state dtype stable so both
            # branches of the guidance cond have the same JAX type.
            return model.action_out_proj(suffix_out[:, -model.action_horizon :]).astype(x_t.dtype)

        def integrate(i: int, x_t: jax.Array) -> jax.Array:
            t = jnp.asarray(1.0 - i / self.num_steps, dtype=jnp.float32)

            def guided(_: None) -> jax.Array:
                def denoiser(x: jax.Array) -> tuple[jax.Array, jax.Array]:
                    v = velocity(x, t)
                    return x - t * v, v

                denoised, pullback, v_t = jax.vjp(denoiser, x_t, has_aux=True)
                error = weights * (reference - denoised)
                correction = pullback(error)[0]
                # Reversing the flow time also reverses the correction sign.
                return v_t - guidance_weight(t, self.max_guidance) * correction

            v_t = jax.lax.cond(
                jnp.any(weights > 0) & (self.max_guidance > 0),
                guided,
                lambda _: velocity(x_t, t),
                operand=None,
            )
            return x_t - v_t / self.num_steps

        return jax.lax.fori_loop(0, self.num_steps, integrate, noise)


class RTCPolicy(base_policy.BasePolicy):
    """Serve true action-expert guidance with OpenPI's original transforms.

    Input keys are standard Piper observations plus the paired optional keys
    ``rtc/reference_actions`` and ``rtc/reference_weights``, both float[h,7].
    Omitting both keys samples without guidance. Outputs are absolute actions
    float[h,7], ``policy_timing`` and an echoed optional ``rtc/request_id``.
    Weight 1 means maximal finite guidance, not an exact equality projection.
    """

    def __init__(
        self,
        trained_policy: Any,
        *,
        norm_stats_path: pathlib.Path,
        num_steps: int = 10,
        max_guidance: float = 5.0,
    ):
        if num_steps < 1:
            raise ValueError("num_steps must be positive")
        if not np.isfinite(max_guidance) or max_guidance < 0:
            raise ValueError("max_guidance must be finite and nonnegative")
        if getattr(trained_policy, "_is_pytorch_model", True):
            raise ValueError("RTC currently requires a JAX/Orbax Pi0 or pi0.5 checkpoint")
        if not isinstance(trained_policy._model, pi0.Pi0):
            raise TypeError("RTC supports Pi0/pi0.5 flow models, not FAST")
        self._base = trained_policy
        self._sampler = RTCSampler(trained_policy._model, num_steps=num_steps, max_guidance=max_guidance)
        self._sample = nnx_utils.module_jit(self._sampler.sample_actions)
        self._rng = jax.random.key(0)
        self._lock = threading.Lock()
        self.horizon = trained_policy._model.action_horizon
        self.model_action_dim = trained_policy._model.action_dim
        if self.model_action_dim < PHYSICAL_ACTION_DIM:
            raise ValueError("Model action dimension is smaller than the Piper action dimension")
        self._metadata = {
            **(trained_policy.metadata or {}),
            "rtc_enabled": True,
            "horizon": self.horizon,
            "action_dim": PHYSICAL_ACTION_DIM,
            "model_action_dim": self.model_action_dim,
            "fps": 30,
            "action_space": "absolute_joint_position",
            "joint_unit": "rad",
            "gripper": "closedness",
            "norm_stats_sha256": hashlib.sha256(norm_stats_path.read_bytes()).hexdigest(),
            "num_steps": num_steps,
            "max_guidance": max_guidance,
            "rtc_weight_semantics": "finite_guidance_not_exact_projection",
        }

    @property
    def metadata(self) -> dict[str, Any]:
        return dict(self._metadata)

    def _reference_array(self, value: Any, name: str) -> np.ndarray:
        result = np.array(value, dtype=np.float32, copy=True)
        if result.shape != (self.horizon, PHYSICAL_ACTION_DIM) or not np.isfinite(result).all():
            raise ValueError(f"{name} must be finite float[{self.horizon},7], got {result.shape}")
        return result

    def infer(self, obs: dict, *, noise: np.ndarray | None = None) -> dict:
        # Policy RNG and the underlying model are shared by all connections.
        with self._lock:
            return self._infer(obs, noise=noise)

    def _infer(self, obs: dict, *, noise: np.ndarray | None) -> dict:
        total_start = time.monotonic()
        has_reference = "rtc/reference_actions" in obs
        if has_reference != ("rtc/reference_weights" in obs):
            raise ValueError("RTC reference actions and weights must be supplied together")
        # Do not allow an unrelated actions field to silently enter transforms.
        inputs = {k: np.array(v, copy=True) if isinstance(v, np.ndarray) else v
                  for k, v in obs.items() if not k.startswith("rtc/") and k != "actions"}
        state = np.asarray(inputs["observation/state"], dtype=np.float32)
        if state.shape != (PHYSICAL_ACTION_DIM,) or not np.isfinite(state).all():
            raise ValueError("observation/state must be finite float[7]")
        inputs["observation/state"] = state.copy()
        if has_reference:
            inputs["actions"] = self._reference_array(obs["rtc/reference_actions"], "reference_actions")
            physical_weights = self._reference_array(obs["rtc/reference_weights"], "reference_weights")
            if np.any((physical_weights < 0) | (physical_weights > 1)):
                raise ValueError("RTC weights must lie in [0,1]")
        else:
            physical_weights = np.zeros((self.horizon, PHYSICAL_ACTION_DIM), dtype=np.float32)

        # PiperInputs -> DeltaActions -> Normalize(checkpoint stats) ->
        # Resize/Tokenize/Pad: reference and state share the exact serving path.
        inputs = self._base._input_transform(inputs)
        reference = np.asarray(inputs.pop("actions"), dtype=np.float32) if has_reference else np.zeros(
            (self.horizon, self.model_action_dim), dtype=np.float32
        )
        if reference.shape != (self.horizon, self.model_action_dim) or not np.isfinite(reference).all():
            raise ValueError("Input transforms produced invalid normalized RTC reference")
        # Padding is never guided, even when all seven physical dimensions are.
        weights = np.zeros_like(reference)
        weights[:, :PHYSICAL_ACTION_DIM] = physical_weights
        batched = jax.tree.map(lambda x: jnp.asarray(x)[None, ...], inputs)
        observation = model_lib.Observation.from_dict(batched)
        self._rng, sample_rng = jax.random.split(self._rng)
        expected_noise_shape = (1, self.horizon, self.model_action_dim)
        if noise is None:
            sample_noise = jax.random.normal(sample_rng, expected_noise_shape)
        else:
            sample_noise = np.asarray(noise, dtype=np.float32)
            if sample_noise.ndim == 2:
                sample_noise = sample_noise[None, ...]
            if sample_noise.shape != expected_noise_shape or not np.isfinite(sample_noise).all():
                raise ValueError(f"noise must be finite with shape {expected_noise_shape} (batch optional)")
            sample_noise = jnp.asarray(sample_noise)
        model_start = time.monotonic()
        sampled = self._sample(
            sample_rng, observation, jnp.asarray(reference)[None], jnp.asarray(weights)[None], sample_noise
        )
        # Synchronize before reporting duration; JAX dispatch is asynchronous.
        sampled.block_until_ready()
        model_ms = (time.monotonic() - model_start) * 1000
        outputs = self._base._output_transform({
            "state": np.asarray(batched["state"][0]),
            "actions": np.asarray(sampled[0]),
        })
        actions = np.asarray(outputs["actions"], dtype=np.float32)
        if actions.shape != (self.horizon, PHYSICAL_ACTION_DIM) or not np.isfinite(actions).all():
            raise ValueError("Output transforms produced invalid absolute Piper actions")
        outputs["actions"] = actions
        outputs["policy_timing"] = {
            "infer_ms": model_ms,
            "total_ms": (time.monotonic() - total_start) * 1000,
        }
        if "rtc/request_id" in obs:
            outputs["rtc/request_id"] = obs["rtc/request_id"]
        return outputs


def create_rtc_policy(
    config_name: str,
    checkpoint: str | pathlib.Path,
    *,
    num_steps: int = 10,
    max_guidance: float = 5.0,
) -> RTCPolicy:
    checkpoint = pathlib.Path(checkpoint).expanduser().resolve()
    if not (checkpoint / "params").is_dir() or not (checkpoint / "assets").is_dir():
        raise ValueError("checkpoint must be the root containing params/ and assets/")
    train_config = training_config.get_config(config_name)
    if not isinstance(train_config.data, training_config.LeRobotPiperDataConfig):
        raise ValueError("RTC service requires LeRobotPiperDataConfig to preserve its seven-dimensional action contract")
    asset_id = train_config.data.assets.asset_id or train_config.data.repo_id
    if not isinstance(asset_id, str) or not asset_id:
        raise ValueError("Training config must resolve a checkpoint normalization asset id")
    norm_stats_path = checkpoint / "assets" / asset_id / "norm_stats.json"
    if not norm_stats_path.is_file():
        raise FileNotFoundError(f"Checkpoint normalization stats are missing: {norm_stats_path}")
    # No stats override: create_trained_policy loads exactly the checkpoint
    # assets identified above, along with the original input/output transforms.
    trained = policy_config.create_trained_policy(train_config, checkpoint)
    policy = RTCPolicy(trained, norm_stats_path=norm_stats_path, num_steps=num_steps, max_guidance=max_guidance)
    policy._metadata["training_config"] = config_name
    return policy
